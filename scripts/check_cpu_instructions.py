    # BIT
    0x24, 0x2C,
    # BRK
    0x00,
    # CLC, CLD, CLI, CLV
    0x18, 0xD8, 0x58, 0xB8,
    # CMP
    0xC9, 0xC5, 0xD5, 0xCD, 0xDD, 0xD9, 0xC1, 0xD1,
    # CPX
    0xE0, 0xE4, 0xEC,
    # CPY
